// Read-only schema introspection restricted to the disposable loopback stack.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import ts from 'typescript';
import { isolatedNativeTargets, isolatedPgEnvironment } from './lib/test-isolated-native-target.mjs';

const { databaseUrl }=isolatedNativeTargets();
const env=isolatedPgEnvironment(databaseUrl);
const cli=process.env.ZARIX_SUPABASE_CLI||'supabase';
const pgBin=process.env.ZARIX_PG_BIN||'';
const output=path.resolve('types/supabase-generated.ts');
const psql=pgBin?path.join(pgBin,'psql'):'psql';
const expected=spawnSync(psql,['-X','-q','-A','-t','-v','ON_ERROR_STOP=1','-c',"SELECT jsonb_agg(tablename ORDER BY tablename) FROM pg_tables WHERE schemaname='public'"],{env,encoding:'utf8'});
if(expected.status!==0)throw new Error('Could not read the local public table inventory');
const expectedTables=JSON.parse(expected.stdout.trim());
assert.ok(expectedTables?.length,'Bootstrap the isolated application schema first');
// The disposable native stack has no TLS listener. Add this fixed transport
// option only after the loopback guard; user-supplied URL options stay refused.
const cliDatabaseUrl=new URL(databaseUrl);
cliDatabaseUrl.searchParams.set('sslmode','disable');
const result=spawnSync(cli,['gen','types','--db-url',cliDatabaseUrl.href,'--schema','public'],{env:process.env,encoding:'utf8',maxBuffer:32*1024*1024});
if(result.error)throw new Error('Official Supabase CLI could not start; connection arguments omitted');
if(result.status!==0)throw new Error('Official Supabase type generation failed; raw diagnostics omitted');
const generated=result.stdout;
const source=ts.createSourceFile('supabase-generated.ts',generated,ts.ScriptTarget.Latest,true);
const database=source.statements.find(node=>ts.isTypeAliasDeclaration(node)&&node.name.text==='Database');
const namedMember=(node,name)=>node?.members?.find(member=>member.name?.getText(source).replaceAll('"','').replaceAll("'",'')===name)?.type;
const publicSchema=namedMember(database?.type,'public');
const tables=namedMember(publicSchema,'Tables');
const names=tables?.members?.map(member=>member.name.getText(source).replaceAll('"','').replaceAll("'",'')).sort();
assert.deepEqual(names,expectedTables,'Generated types must cover every live public application table');
const transactions=namedMember(namedMember(tables,'transactions'),'Row');
const accounts=namedMember(namedMember(tables,'accounts'),'Row');
assert.ok(namedMember(transactions,'destination_amount_in_account_currency'),'Missing authoritative destination amount type');
assert.ok(namedMember(accounts,'movement_enabled'),'Missing movement allowance field type');
const functions=namedMember(publicSchema,'Functions');
for(const name of ['save_shared_expense','sell_investment_position','create_transaction_once','sell_investment_once','save_shared_expense_once','recompute_account_balance'])assert.ok(namedMember(functions,name),`Missing RPC ${name}`);
const recomputeArgs=namedMember(namedMember(functions,'recompute_account_balance'),'Args');
assert.equal(namedMember(recomputeArgs,'p_user_id')?.getText(source),'string','Missing owner UUID parameter');
assert.equal(namedMember(recomputeArgs,'p_account_id')?.getText(source),'string','Missing account UUID parameter');
const text='// Generated by scripts/generate-isolated-database-types.mjs from disposable local PostgreSQL.\n// Public schema contract; display models remain in database.ts.\n'+generated.trimEnd()+'\n';
if(process.argv.includes('--write'))await fs.writeFile(output,text);
else assert.equal(await fs.readFile(output,'utf8'),text,'Database types differ from the local schema; rerun with --write');
console.log(JSON.stringify({status:'PASS',mode:process.argv.includes('--write')?'write':'check',source:'loopback public schema via official Supabase CLI',tables:names.length,functions:functions.members.length,sha256:createHash('sha256').update(text).digest('hex'),file:'types/supabase-generated.ts'}));
